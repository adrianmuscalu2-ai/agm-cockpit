import assert from 'node:assert/strict';
import { readRecognitionTranscript, selectSpeechVoice, speechRecognitionFailure, waitForSpeechVoice } from '../src/turn-agmatcc/agmatcc.speech';
const arrayLike = { length: 2, 0: { isFinal: true, 0: { transcript: 'Ce incidente' } }, 1: { isFinal: false, 0: { transcript: 'sunt active?' } } };
assert.deepEqual(readRecognitionTranscript({ results: arrayLike }), { text: 'Ce incidente sunt active?', final: '' });
arrayLike[1].isFinal = true;
assert.equal(readRecognitionTranscript({ results: arrayLike }).final, 'Ce incidente sunt active?');
assert.deepEqual(readRecognitionTranscript({ results: { length: 0 } }), { text: '', final: '' });
const voices = [{ lang: 'en-US', default: true }, { lang: 'ro-RO' }];
assert.equal(selectSpeechVoice(voices, 'ro-RO'), voices[1]);
assert.equal(selectSpeechVoice([voices[0]], 'ro-RO'), undefined, 'never read Romanian through unrelated default voice');
assert.ok(speechRecognitionFailure('network').includes('browserului'));
assert.ok(speechRecognitionFailure('not-allowed').includes('microfon'));
const synthesis = new EventTarget() as EventTarget & { getVoices: () => typeof voices };
synthesis.getVoices = () => [];
const loaded = waitForSpeechVoice(synthesis as unknown as SpeechSynthesis, 'ro-RO');
synthesis.getVoices = () => voices;
synthesis.dispatchEvent(new Event('voiceschanged'));
assert.equal(await loaded, voices[1]);
console.log('PASS speech unit: non-iterable STT results, interim/final boundaries, empty capture, Romanian voice selection/loading, separate STT error causes; physical audio NOT tested');
